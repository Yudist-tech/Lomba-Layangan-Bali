-- =====================================================================
-- ISTIRAHAT DI JADWAL TERBANG (versi 1.0)
-- Jalankan SETELAH multi-event.sql. Aman dijalankan ulang (idempotent).
-- Hanya MENAMBAH tabel & fungsi baru — data lama tidak diubah / dihapus.
--
-- lomba_istirahat : baris "ISTIRAHAT" berwarna di tabel jadwal, diletakkan
--                   setelah satu seri (lomba_sesi). Tampil di dashboard
--                   panitia, halaman jadwal peserta, dan hasil cetak.
--                   Ikut terhapus bila seri / hari-nya dihapus.
-- =====================================================================

create table if not exists public.lomba_istirahat (
  id           bigint generated by default as identity primary key,
  event_id     bigint not null references public.lomba_event(id) on delete cascade,
  sesi_id      bigint not null references public.lomba_sesi(id) on delete cascade,   -- letak: setelah seri ini
  jam_mulai    time,
  jam_selesai  time,
  warna        text not null default 'kuning'
               check (warna in ('kuning', 'hijau', 'biru', 'ungu', 'merah', 'abu', 'hitam')),
  created_at   timestamptz not null default now()
);
create index if not exists lomba_istirahat_event_idx on public.lomba_istirahat (event_id);
create index if not exists lomba_istirahat_sesi_idx  on public.lomba_istirahat (sesi_id);

-- event_id selalu diambil dari seri-nya (tidak bisa dipasang ke event lain)
create or replace function public.lomba_trg_istirahat()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  select s.event_id into new.event_id from public.lomba_sesi s where s.id = new.sesi_id;
  if new.event_id is null then
    raise exception 'Seri tidak ditemukan';
  end if;
  if new.jam_mulai is not null and new.jam_selesai is not null and new.jam_selesai <= new.jam_mulai then
    raise exception 'Jam selesai istirahat harus setelah jam mulai';
  end if;
  return new;
end;
$$;
drop trigger if exists lomba_istirahat_biu on public.lomba_istirahat;
create trigger lomba_istirahat_biu before insert or update on public.lomba_istirahat
  for each row execute function public.lomba_trg_istirahat();

-- keamanan: sama seperti seri — hanya panitia event itu
alter table public.lomba_istirahat enable row level security;
drop policy if exists lomba_admin_kelola on public.lomba_istirahat;
create policy lomba_admin_kelola on public.lomba_istirahat for all to authenticated
  using ((select public.lomba_boleh_event(event_id)))
  with check ((select public.lomba_boleh_event(event_id)));
revoke all on table public.lomba_istirahat from anon;
grant select, insert, update, delete on table public.lomba_istirahat to authenticated;
grant select, insert, update, delete on table public.lomba_istirahat to service_role;

-- halaman peserta: baca istirahat event (tanpa login)
create or replace function public.lomba_istirahat_publik(p_event bigint default null)
returns json
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(json_agg(json_build_object('id', i.id, 'sesi_id', i.sesi_id, 'jam_mulai', i.jam_mulai,
                                             'jam_selesai', i.jam_selesai, 'warna', i.warna)
                           order by i.jam_mulai nulls last, i.id), '[]'::json)
    from public.lomba_istirahat i
   where i.event_id = public.lomba_ev(p_event);
$$;
revoke all on function public.lomba_istirahat_publik(bigint) from public;
grant execute on function public.lomba_istirahat_publik(bigint) to anon, authenticated;

-- Pemeriksaan
select '✅ Tabel istirahat siap' as hasil
where to_regclass('public.lomba_istirahat') is not null
union all
select '✅ Istirahat tampil di halaman peserta'
where exists (select 1 from pg_proc where proname = 'lomba_istirahat_publik');
