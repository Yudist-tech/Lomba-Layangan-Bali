-- =====================================================================
-- JURI PANTAU (versi 1.0)
-- Jalankan SETELAH juara.sql. Aman dijalankan ulang (idempotent).
--
-- 1) lomba_juri_pantau   : daftar nama juri pantau per event (diketik sekali
--                          di jendela "Cetak lembar juri pantau").
-- 2) lomba_catatan_pantau: catatan juri pantau per layangan (dari upload foto
--                          lembar, atau diketik panitia). Tampil di kolom
--                          "Keterangan juri pantau" halaman Penilaian.
--                          Hanya untuk panitia — TIDAK tampil di halaman publik
--                          dan TIDAK mengubah nilai.
-- Baca: semua panitia event. Tambah/ubah/hapus: panitia penilai.
-- =====================================================================

create table if not exists public.lomba_juri_pantau (
  id          bigint generated by default as identity primary key,
  event_id    bigint not null references public.lomba_event(id) on delete cascade,
  nama        text not null check (length(btrim(nama)) between 1 and 40),
  created_at  timestamptz not null default now()
);
create unique index if not exists lomba_juri_pantau_nama_uq on public.lomba_juri_pantau (event_id, lower(btrim(nama)));

create table if not exists public.lomba_catatan_pantau (
  id              bigint generated by default as identity primary key,
  event_id        bigint not null references public.lomba_event(id) on delete cascade,
  pendaftaran_id  uuid not null references public.lomba_pendaftaran(id) on delete cascade,
  pantau_id       bigint not null references public.lomba_juri_pantau(id) on delete cascade,
  teks            text not null default '',     -- keterangan (dipisah koma), bisa dikoreksi panitia
  teks_baca       text,                         -- hasil baca asli dari foto (tidak diubah)
  ragu            boolean not null default false, -- tulisan kurang jelas → perlu dicek
  lembar          int,                          -- nomor lembar & baris di kertas (dari upload)
  baris           int,
  foto_url        text,                         -- potongan foto tulisan asli
  oleh            text,
  updated_at      timestamptz not null default now()
);
create index if not exists lomba_catatan_pantau_event_idx on public.lomba_catatan_pantau (event_id);
create index if not exists lomba_juri_pantau_event_idx on public.lomba_juri_pantau (event_id);

do $$
declare t text;
begin
  foreach t in array array['lomba_juri_pantau', 'lomba_catatan_pantau'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists lomba_baca on public.%I', t);
    execute format('drop policy if exists lomba_menilai_tambah on public.%I', t);
    execute format('drop policy if exists lomba_menilai_ubah on public.%I', t);
    execute format('drop policy if exists lomba_menilai_hapus on public.%I', t);
    execute format('create policy lomba_baca on public.%I for select to authenticated using ((select public.lomba_boleh_event(event_id)))', t);
    execute format('create policy lomba_menilai_tambah on public.%I for insert to authenticated with check ((select public.lomba_boleh_menilai(event_id)))', t);
    execute format('create policy lomba_menilai_ubah on public.%I for update to authenticated using ((select public.lomba_boleh_menilai(event_id))) with check ((select public.lomba_boleh_menilai(event_id)))', t);
    execute format('create policy lomba_menilai_hapus on public.%I for delete to authenticated using ((select public.lomba_boleh_menilai(event_id)))', t);
    execute format('revoke all on table public.%I from anon', t);
    execute format('grant select, insert, update, delete on table public.%I to authenticated', t);
  end loop;
end $$;

-- catatan harus milik event yang sama dengan layangan & juri pantaunya; "oleh" & waktu diisi database
create or replace function public.lomba_trg_catatan_pantau()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (select 1 from public.lomba_pendaftaran where id = new.pendaftaran_id and event_id = new.event_id)
     or not exists (select 1 from public.lomba_juri_pantau where id = new.pantau_id and event_id = new.event_id) then
    raise exception 'JUARA_TIDAK_VALID';
  end if;
  new.teks := left(btrim(coalesce(new.teks, '')), 300);
  new.oleh := public.lomba_email_saya();
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists lomba_catatan_pantau_biu on public.lomba_catatan_pantau;
create trigger lomba_catatan_pantau_biu before insert or update on public.lomba_catatan_pantau
  for each row execute function public.lomba_trg_catatan_pantau();
revoke all on function public.lomba_trg_catatan_pantau() from public, anon, authenticated;

-- Pemeriksaan
select '✅ Tabel juri pantau siap' as hasil
where exists (select 1 from information_schema.tables where table_schema = 'public' and table_name = 'lomba_juri_pantau')
union all
select '✅ Tabel catatan juri pantau siap'
where exists (select 1 from information_schema.tables where table_schema = 'public' and table_name = 'lomba_catatan_pantau')
union all
select '✅ Pemeriksa catatan aktif'
where exists (select 1 from pg_trigger where tgname = 'lomba_catatan_pantau_biu');
