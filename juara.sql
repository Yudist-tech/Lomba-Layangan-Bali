-- =====================================================================
-- PENGUMUMAN JUARA (versi 1.0) — input manual oleh panitia
-- Jalankan SETELAH multi-event.sql. Aman dijalankan ulang (idempotent).
--
-- Panitia memilih juara per jenis layangan: Juara 1–3 dan Harapan 1, 2, 3, …
-- Hanya pendaftaran TERKONFIRMASI di jenis yang sama yang boleh dipilih.
-- Juara baru terlihat publik setelah panitia menekan "Umumkan juara".
-- =====================================================================

-- 1) penanda sudah diumumkan (kosong = masih draf)
alter table public.lomba_pengaturan add column if not exists juara_diumumkan_at timestamptz;

-- 2) daftar juara
create table if not exists public.lomba_juara (
  id              bigint generated by default as identity primary key,
  event_id        bigint not null references public.lomba_event(id) on delete cascade,
  jenis           text not null,
  kelas           text not null check (kelas in ('juara', 'harapan')),
  urutan          int  not null check (urutan between 1 and 50),
  pendaftaran_id  uuid not null references public.lomba_pendaftaran(id) on delete cascade,
  oleh            text,
  created_at      timestamptz not null default now(),
  unique (event_id, jenis, kelas, urutan),
  unique (event_id, pendaftaran_id)
);
create index if not exists lomba_juara_event_idx on public.lomba_juara (event_id);

alter table public.lomba_juara enable row level security;
drop policy if exists lomba_admin_kelola on public.lomba_juara;
create policy lomba_admin_kelola on public.lomba_juara for all to authenticated
  using ((select public.lomba_boleh_event(event_id)))
  with check ((select public.lomba_boleh_event(event_id)));

-- 3) dijaga database: pendaftaran harus terkonfirmasi, di event & jenis yang sama; "oleh" diisi otomatis
create or replace function public.lomba_trg_juara()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  p public.lomba_pendaftaran%rowtype;
begin
  select * into p from public.lomba_pendaftaran where id = new.pendaftaran_id;
  if not found or p.event_id <> new.event_id or p.jenis <> new.jenis then
    raise exception 'JUARA_TIDAK_VALID';
  end if;
  if p.status <> 'terkonfirmasi' then
    raise exception 'JUARA_BELUM_TERKONFIRMASI';
  end if;
  if new.kelas = 'juara' and new.urutan > 3 then
    raise exception 'JUARA_TIDAK_VALID';
  end if;
  new.oleh := public.lomba_email_saya();
  new.created_at := now();
  return new;
end;
$$;
drop trigger if exists lomba_juara_biu on public.lomba_juara;
create trigger lomba_juara_biu before insert or update on public.lomba_juara
  for each row execute function public.lomba_trg_juara();

revoke all on table public.lomba_juara from anon;
grant select, insert, update, delete on table public.lomba_juara to authenticated;
revoke all on function public.lomba_trg_juara() from public, anon, authenticated;

-- 4) halaman publik: juara hanya terlihat setelah diumumkan
create or replace function public.lomba_juara_publik(p_event bigint default null)
returns json
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_ev bigint := public.lomba_ev(p_event);
  v_at timestamptz;
begin
  select juara_diumumkan_at into v_at from public.lomba_pengaturan where event_id = v_ev;
  if v_at is null then
    return json_build_object('diumumkan', false, 'list', '[]'::json);
  end if;
  return json_build_object('diumumkan', true, 'diumumkan_at', v_at, 'list', coalesce((
    select json_agg(json_build_object(
             'jenis', j.jenis, 'kelas', j.kelas, 'urutan', j.urutan,
             'nomor', p.nomor_layangan, 'sekha', p.nama_sekha, 'alamat', p.alamat)
           order by j.jenis, j.kelas desc, j.urutan)
      from public.lomba_juara j join public.lomba_pendaftaran p on p.id = j.pendaftaran_id
     where j.event_id = v_ev and p.status = 'terkonfirmasi'), '[]'::json));
end;
$$;
revoke all on function public.lomba_juara_publik(bigint) from public;
grant execute on function public.lomba_juara_publik(bigint) to anon, authenticated;

-- 5) halaman semua event: tanda "juara diumumkan"
create or replace function public.lomba_ringkas_event(p_event bigint, p_admin boolean default false)
returns json
language sql
stable
security definer
set search_path = public
as $$
  with e as (select * from public.lomba_event where id = p_event),
       st as (select * from public.lomba_pengaturan where event_id = p_event),
       aktif as (select seri_id, count(*) as n from public.lomba_pendaftaran
                  where event_id = p_event and status in ('menunggu', 'terkonfirmasi') group by seri_id),
       grup as (select g.* from public.lomba_seri g where g.event_id = p_event and g.sesi_id is not null and g.aktif)
  select json_build_object(
    'id', e.id, 'slug', e.slug, 'tampil', e.tampil,
    'nama_event', st.nama_event, 'penyelenggara', st.penyelenggara, 'lokasi', st.lokasi,
    'logo_url', st.logo_url, 'bg_url', st.bg_url, 'flyer_url', st.flyer_url,
    'tanggal_mulai', st.tanggal_mulai, 'tanggal_selesai', coalesce(st.tanggal_selesai, st.tanggal_mulai),
    'pendaftaran_buka', coalesce(st.pendaftaran_buka and (st.batas_daftar is null or now() <= st.batas_daftar), false),
    'ada_jadwal', exists (select 1 from grup),
    'sisa_slot', coalesce((select sum(greatest(0, g.kuota - coalesce(a.n, 0))) from grup g left join aktif a on a.seri_id = g.id), 0),
    'jumlah_jenis', (select count(*) from public.lomba_jenis j where j.event_id = p_event and j.aktif),
    'harga_min', (select min(j.harga) from public.lomba_jenis j where j.event_id = p_event and j.aktif),
    'peserta', (select count(*) from public.lomba_pendaftaran p where p.event_id = p_event and p.status = 'terkonfirmasi'),
    'juara_diumumkan', st.juara_diumumkan_at is not null,
    'menunggu', case when p_admin then (select count(*) from public.lomba_pendaftaran p where p.event_id = p_event and p.status = 'menunggu') end,
    'pemasukan', case when p_admin then (select coalesce(sum(p.harga), 0) from public.lomba_pendaftaran p where p.event_id = p_event and p.status = 'terkonfirmasi') end,
    'panitia', case when p_admin and public.lomba_is_super()
                    then coalesce((select json_agg(ea.email order by ea.email) from public.lomba_event_admin ea where ea.event_id = p_event), '[]'::json) end)
  from e left join st on true;
$$;

-- Pemeriksaan
select '✅ Tabel juara siap' as hasil
where exists (select 1 from information_schema.tables where table_schema = 'public' and table_name = 'lomba_juara')
union all
select '✅ Pengumuman publik siap'
where exists (select 1 from pg_proc where proname = 'lomba_juara_publik')
union all
select '✅ Halaman semua event membaca status juara'
where pg_get_functiondef('public.lomba_ringkas_event(bigint, boolean)'::regprocedure) like '%juara_diumumkan%';
