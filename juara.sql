-- =====================================================================
-- PENILAIAN & PENGUMUMAN JUARA (versi 1.0)
-- Jalankan SETELAH multi-event.sql. Aman dijalankan ulang (idempotent).
--
-- Penilaian: panitia mencari layangan yang dinilai, memasukkan nilai tiap juri
-- (angka bulat, batas bawaan 100), sistem menjumlah & mengurutkan per jenis.
-- Diskualifikasi wajib beralasan. Hasil dijadikan juara (Juara 1–3, Harapan 1…)
-- lalu baru terlihat publik setelah panitia menekan "Umumkan juara" — PER JENIS
-- (jenis yang sudah selesai dinilai bisa diumumkan lebih dulu).
-- Keamanan: hanya panitia penilai yang bisa mengubah nilai, nilai terkunci
-- setelah diumumkan, dan setiap perubahan tercatat (bagian 6).
-- Hanya pendaftaran TERKONFIRMASI yang bisa dinilai / menjadi juara.
-- =====================================================================

-- 1) penanda jenis yang juaranya sudah diumumkan (tidak ada baris = masih draf)
create table if not exists public.lomba_juara_umum (
  event_id      bigint not null references public.lomba_event(id) on delete cascade,
  jenis         text not null,
  diumumkan_at  timestamptz not null default now(),
  oleh          text,
  primary key (event_id, jenis)
);
alter table public.lomba_juara_umum enable row level security;
drop policy if exists lomba_admin_kelola on public.lomba_juara_umum;
create policy lomba_admin_kelola on public.lomba_juara_umum for all to authenticated
  using ((select public.lomba_boleh_event(event_id)))
  with check ((select public.lomba_boleh_event(event_id)));
grant select, insert, update, delete on public.lomba_juara_umum to authenticated;
create or replace function public.lomba_trg_juara_umum()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.oleh := public.lomba_email_saya();
  return new;
end;
$$;
drop trigger if exists lomba_juara_umum_biu on public.lomba_juara_umum;
create trigger lomba_juara_umum_biu before insert or update on public.lomba_juara_umum
  for each row execute function public.lomba_trg_juara_umum();
revoke all on function public.lomba_trg_juara_umum() from public, anon, authenticated;

-- 2) daftar juara
create table if not exists public.lomba_juara (
  id              bigint generated by default as identity primary key,
  event_id        bigint not null references public.lomba_event(id) on delete cascade,
  jenis           text not null,
  kelas           text not null check (kelas in ('juara', 'harapan')),
  urutan          int  not null check (urutan between 1 and 50),
  pendaftaran_id  uuid not null references public.lomba_pendaftaran(id) on delete cascade,
  oleh            text,
  created_at      timestamptz not null default now(),
  unique (event_id, jenis, kelas, urutan),
  unique (event_id, pendaftaran_id)
);
create index if not exists lomba_juara_event_idx on public.lomba_juara (event_id);

alter table public.lomba_juara enable row level security;
drop policy if exists lomba_admin_kelola on public.lomba_juara;
create policy lomba_admin_kelola on public.lomba_juara for all to authenticated
  using ((select public.lomba_boleh_event(event_id)))
  with check ((select public.lomba_boleh_event(event_id)));

-- 3) dijaga database: pendaftaran harus terkonfirmasi, di event & jenis yang sama; "oleh" diisi otomatis
create or replace function public.lomba_trg_juara()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  p public.lomba_pendaftaran%rowtype;
begin
  select * into p from public.lomba_pendaftaran where id = new.pendaftaran_id;
  if not found or p.event_id <> new.event_id or p.jenis <> new.jenis then
    raise exception 'JUARA_TIDAK_VALID';
  end if;
  if p.status <> 'terkonfirmasi' then
    raise exception 'JUARA_BELUM_TERKONFIRMASI';
  end if;
  if new.kelas = 'juara' and new.urutan > 3 then
    raise exception 'JUARA_TIDAK_VALID';
  end if;
  new.oleh := public.lomba_email_saya();
  new.created_at := now();
  return new;
end;
$$;
drop trigger if exists lomba_juara_biu on public.lomba_juara;
create trigger lomba_juara_biu before insert or update on public.lomba_juara
  for each row execute function public.lomba_trg_juara();

revoke all on table public.lomba_juara from anon;
grant select, insert, update, delete on table public.lomba_juara to authenticated;
revoke all on function public.lomba_trg_juara() from public, anon, authenticated;


-- 2b) PENILAIAN -------------------------------------------------------
alter table public.lomba_pengaturan add column if not exists nilai_maks int not null default 100;

create table if not exists public.lomba_juri (
  id        bigint generated by default as identity primary key,
  event_id  bigint not null references public.lomba_event(id) on delete cascade,
  urutan    int not null,
  nama      text not null default '',
  unique (event_id, urutan)
);
