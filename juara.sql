    execute format('create policy lomba_admin_kelola on public.%I for all to authenticated using ((select public.lomba_boleh_event(event_id))) with check ((select public.lomba_boleh_event(event_id)))', t);
    execute format('revoke all on table public.%I from anon', t);
    execute format('grant select, insert, update, delete on table public.%I to authenticated', t);
  end loop;
end $$;

create or replace function public.lomba_trg_penilaian()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  p public.lomba_pendaftaran%rowtype;
begin
  select * into p from public.lomba_pendaftaran where id = new.pendaftaran_id;
  if not found or p.event_id <> new.event_id then raise exception 'JUARA_TIDAK_VALID'; end if;
  if p.status <> 'terkonfirmasi' then raise exception 'JUARA_BELUM_TERKONFIRMASI'; end if;
  new.alasan := nullif(btrim(coalesce(new.alasan, '')), '');
  if new.diskualifikasi and new.alasan is null then raise exception 'ALASAN_DISKUALIFIKASI'; end if;
  if not new.diskualifikasi then new.alasan := null; end if;
  new.oleh := public.lomba_email_saya();
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists lomba_penilaian_biu on public.lomba_penilaian;
create trigger lomba_penilaian_biu before insert or update on public.lomba_penilaian
  for each row execute function public.lomba_trg_penilaian();

create or replace function public.lomba_trg_nilai()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_maks int;
begin
  if not exists (select 1 from public.lomba_juri where id = new.juri_id and event_id = new.event_id)
     or not exists (select 1 from public.lomba_penilaian where pendaftaran_id = new.pendaftaran_id and event_id = new.event_id) then
    raise exception 'JUARA_TIDAK_VALID';
  end if;
  select coalesce(nilai_maks, 100) into v_maks from public.lomba_pengaturan where event_id = new.event_id;
  if new.nilai > coalesce(v_maks, 100) then raise exception 'NILAI_TERLALU_BESAR'; end if;
  new.oleh := public.lomba_email_saya();
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists lomba_nilai_biu on public.lomba_nilai;
create trigger lomba_nilai_biu before insert or update on public.lomba_nilai
  for each row execute function public.lomba_trg_nilai();

revoke all on function public.lomba_trg_penilaian() from public, anon, authenticated;
revoke all on function public.lomba_trg_nilai() from public, anon, authenticated;

-- 4) halaman publik: juara sebuah jenis hanya terlihat setelah jenis itu diumumkan
create or replace function public.lomba_juara_publik(p_event bigint default null)
returns json
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_ev bigint := public.lomba_ev(p_event);
begin
  if not exists (select 1 from public.lomba_juara_umum where event_id = v_ev) then
    return json_build_object('diumumkan', false, 'jenis', '[]'::json, 'list', '[]'::json);
  end if;
  return json_build_object('diumumkan', true,
    'jenis', (select json_agg(json_build_object('jenis', u.jenis, 'diumumkan_at', u.diumumkan_at) order by u.diumumkan_at)
                from public.lomba_juara_umum u where u.event_id = v_ev),
    'list', coalesce((
    select json_agg(json_build_object(
             'jenis', j.jenis, 'kelas', j.kelas, 'urutan', j.urutan,
             'nomor', p.nomor_layangan, 'sekha', p.nama_sekha, 'alamat', p.alamat, 'foto', pn.foto_url)
           order by j.jenis, j.kelas desc, j.urutan)
      from public.lomba_juara j
      join public.lomba_pendaftaran p on p.id = j.pendaftaran_id
      join public.lomba_juara_umum u on u.event_id = j.event_id and u.jenis = j.jenis
      left join public.lomba_penilaian pn on pn.pendaftaran_id = j.pendaftaran_id
     where j.event_id = v_ev and p.status = 'terkonfirmasi'), '[]'::json));
end;
$$;
revoke all on function public.lomba_juara_publik(bigint) from public;
grant execute on function public.lomba_juara_publik(bigint) to anon, authenticated;

-- 5) halaman semua event: tanda "juara diumumkan"
create or replace function public.lomba_ringkas_event(p_event bigint, p_admin boolean default false)
returns json
language sql
stable
security definer
set search_path = public
as $$
  with e as (select * from public.lomba_event where id = p_event),
       st as (select * from public.lomba_pengaturan where event_id = p_event),
       aktif as (select seri_id, count(*) as n from public.lomba_pendaftaran
                  where event_id = p_event and status in ('menunggu', 'terkonfirmasi') group by seri_id),
       grup as (select g.* from public.lomba_seri g where g.event_id = p_event and g.sesi_id is not null and g.aktif)
  select json_build_object(
    'id', e.id, 'slug', e.slug, 'tampil', e.tampil,
    'nama_event', st.nama_event, 'penyelenggara', st.penyelenggara, 'lokasi', st.lokasi,
    'logo_url', st.logo_url, 'bg_url', st.bg_url, 'flyer_url', st.flyer_url,
    'tanggal_mulai', st.tanggal_mulai, 'tanggal_selesai', coalesce(st.tanggal_selesai, st.tanggal_mulai),
    'pendaftaran_buka', coalesce(st.pendaftaran_buka and (st.batas_daftar is null or now() <= st.batas_daftar), false),
    'ada_jadwal', exists (select 1 from grup),
    'sisa_slot', coalesce((select sum(greatest(0, g.kuota - coalesce(a.n, 0))) from grup g left join aktif a on a.seri_id = g.id), 0),
    'jumlah_jenis', (select count(*) from public.lomba_jenis j where j.event_id = p_event and j.aktif),
    'harga_min', (select min(j.harga) from public.lomba_jenis j where j.event_id = p_event and j.aktif),
    'peserta', (select count(*) from public.lomba_pendaftaran p where p.event_id = p_event and p.status = 'terkonfirmasi'),
    'juara_diumumkan', exists (select 1 from public.lomba_juara_umum u where u.event_id = p_event),
    'menunggu', case when p_admin then (select count(*) from public.lomba_pendaftaran p where p.event_id = p_event and p.status = 'menunggu') end,
    'pemasukan', case when p_admin then (select coalesce(sum(p.harga), 0) from public.lomba_pendaftaran p where p.event_id = p_event and p.status = 'terkonfirmasi') end,
    'panitia', case when p_admin and public.lomba_is_super()
                    then coalesce((select json_agg(ea.email order by ea.email) from public.lomba_event_admin ea where ea.event_id = p_event), '[]'::json) end)
  from e left join st on true;
$$;

