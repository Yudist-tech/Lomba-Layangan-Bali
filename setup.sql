alter table public.lomba_pendaftaran add column if not exists kotak int;
create unique index if not exists lomba_pendaftaran_kotak_uidx on public.lomba_pendaftaran (seri_id, kotak)
  where kotak is not null and status in ('menunggu', 'terkonfirmasi');

-- v2: nomor layangan diisi peserta, unik PER JENIS (yang ditolak melepas nomornya)
alter table public.lomba_pendaftaran drop constraint if exists lomba_pendaftaran_nomor_layangan_key;
create unique index if not exists lomba_pendaftaran_nomor_uidx on public.lomba_pendaftaran (jenis, nomor_layangan)
  where nomor_layangan is not null and status in ('menunggu', 'terkonfirmasi');


