-- Info event, harga, jadwal seri + sisa kuota (tanpa data pribadi peserta)
create or replace function public.lomba_info_publik()
returns json
language sql
stable
security definer
set search_path = public
as $$
  with st as (
    select * from public.lomba_pengaturan where id = 1
  ),
  hit as (
    select seri_id, count(*) filter (where status in ('menunggu', 'terkonfirmasi')) as terisi
    from public.lomba_pendaftaran
    group by seri_id
  )
  select json_build_object(
    'event', (
      select json_build_object(
        'nama_event', nama_event,
        'penyelenggara', penyelenggara,
        'lokasi', lokasi,
        'info', info,
        'wa_admin', wa_admin,
        'bank_nama', bank_nama,
        'bank_no_rek', bank_no_rek,
        'bank_atas_nama', bank_atas_nama,
        'pendaftaran_buka', pendaftaran_buka and (batas_daftar is null or now() <= batas_daftar),
        'batas_daftar', batas_daftar,
        'tampilkan_peserta', tampilkan_peserta,
        'logo_url', logo_url,
        'bg_url', bg_url
      ) from st
    ),
    'jenis', coalesce((
      select json_agg(json_build_object(
               'kode', j.kode, 'nama', j.nama, 'harga', j.harga,
               'prefix', j.prefix, 'aktif', j.aktif)
             order by j.urutan, j.nama)
      from public.lomba_jenis j
    ), '[]'::json),
    'seri', coalesce((
      select json_agg(json_build_object(
               'id', s.id, 'jenis', s.jenis, 'nama', s.nama, 'tanggal', s.tanggal,
               'jam_mulai', s.jam_mulai, 'jam_selesai', s.jam_selesai,
               'kuota', s.kuota, 'aktif', s.aktif, 'catatan', s.catatan,
               'terisi', coalesce(h.terisi, 0),
               'peserta', case when (select tampilkan_peserta from st) then (
                   select coalesce(json_agg(json_build_object('nomor', p.nomor_layangan, 'sekha', p.nama_sekha)
                                            order by p.nomor_urut nulls last, p.nama_sekha), '[]'::json)
                   from public.lomba_pendaftaran p
                   where p.seri_id = s.id and p.status = 'terkonfirmasi'
                 ) end)
             order by s.tanggal nulls last, s.jam_mulai nulls last, s.urutan, s.id)
      from public.lomba_seri s
      left join hit h on h.seri_id = s.id
    ), '[]'::json),
    'waktu_server', now()
  );
$$;

-- Simpan pendaftaran baru (status selalu "menunggu" verifikasi)
drop function if exists public.lomba_daftar(text, bigint, text, text, text, text, text, text, uuid);
create or replace function public.lomba_daftar(
  p_jenis          text,
  p_seri_id        bigint,
  p_nama_sekha     text,
  p_alamat         text,
  p_no_wa          text,
  p_nama_rekening  text,
  p_bukti_path     text,
  p_bukti_hash     text default null,
  p_client_ref     uuid default null,
  p_harga          integer default null
)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_set    public.lomba_pengaturan%rowtype;
  v_jenis  public.lomba_jenis%rowtype;
  v_seri   public.lomba_seri%rowtype;
  v_row    public.lomba_pendaftaran%rowtype;
  v_wa     text;
  v_ip     text;
  v_iphash text;
  v_ada    boolean;
begin
  -- kirim ulang (mis. koneksi putus) → kembalikan pendaftaran yang sama, tidak dobel
  if p_client_ref is not null then
    select * into v_row from public.lomba_pendaftaran where client_ref = p_client_ref;
    if found then
      return json_build_object('kode', v_row.kode, 'status', v_row.status, 'harga', v_row.harga,
                               'created_at', v_row.created_at, 'no_wa', v_row.no_wa,
                               'jenis', v_row.jenis, 'seri_id', v_row.seri_id, 'nama_sekha', v_row.nama_sekha);
    end if;
  end if;

  select * into v_set from public.lomba_pengaturan where id = 1;
  if not found or not v_set.pendaftaran_buka
     or (v_set.batas_daftar is not null and now() > v_set.batas_daftar) then
    raise exception 'PENDAFTARAN_DITUTUP';
  end if;

  select * into v_jenis from public.lomba_jenis where kode = p_jenis;
  if not found or not v_jenis.aktif then
    raise exception 'JENIS_TIDAK_VALID';
  end if;

  -- harga yang dilihat peserta harus sama dengan harga saat ini
  if p_harga is not null and p_harga <> v_jenis.harga then
    raise exception 'HARGA_BERUBAH';
  end if;

  select * into v_seri from public.lomba_seri where id = p_seri_id;
  if not found or v_seri.jenis <> p_jenis or not v_seri.aktif then
    raise exception 'SERI_TIDAK_VALID';
  end if;

  if char_length(btrim(coalesce(p_nama_sekha, ''))) not between 2 and 120
     or char_length(btrim(coalesce(p_alamat, ''))) not between 3 and 300
     or char_length(btrim(coalesce(p_nama_rekening, ''))) not between 2 and 120 then
    raise exception 'DATA_TIDAK_LENGKAP';
  end if;

  v_wa := public.lomba_normalisasi_wa(p_no_wa);
  if v_wa is null then
    raise exception 'WA_TIDAK_VALID';
  end if;

  if p_bukti_path is null
     or p_bukti_path !~ '^bukti/[0-9a-f-]{36}\.(jpg|jpeg|png|webp|pdf)$' then
    raise exception 'BUKTI_TIDAK_VALID';
  end if;

  -- file bukti harus benar-benar sudah terunggah ke Storage
  begin
    select exists (select 1 from storage.objects
                   where bucket_id = 'lomba-bukti' and name = p_bukti_path) into v_ada;
  exception when others then
    v_ada := true;   -- bila Storage tidak bisa dibaca, jangan blokir pendaftaran
  end;
  if not v_ada then
    raise exception 'BUKTI_TIDAK_VALID';
  end if;

  -- rem anti-spam: maks 15 pendaftaran per nomor WA per jam
  if (select count(*) from public.lomba_pendaftaran
      where no_wa = v_wa and created_at > now() - interval '1 hour') >= 15 then
    raise exception 'TERLALU_BANYAK';
  end if;

  -- rem anti-spam: maks 30 pendaftaran per jaringan (IP) per 10 menit
  begin
    v_ip := nullif(btrim(split_part(coalesce(
              current_setting('request.headers', true)::json ->> 'cf-connecting-ip',
              current_setting('request.headers', true)::json ->> 'x-forwarded-for',
              current_setting('request.headers', true)::json ->> 'x-real-ip', ''), ',', 1)), '');
  exception when others then
    v_ip := null;
  end;
  if v_ip is not null then
    v_iphash := left(encode(sha256(convert_to('lomba:' || v_ip, 'UTF8')), 'hex'), 16);
    if (select count(*) from public.lomba_pendaftaran
        where ip_hash = v_iphash and created_at > now() - interval '10 minutes') >= 30 then
      raise exception 'TERLALU_BANYAK';
    end if;
  end if;

  insert into public.lomba_pendaftaran
    (client_ref, jenis, seri_id, nama_sekha, alamat, no_wa, nama_rekening,
     bukti_path, bukti_hash, harga, status, ip_hash)
  values
    (p_client_ref, p_jenis, p_seri_id, p_nama_sekha, p_alamat, v_wa, p_nama_rekening,
     p_bukti_path, left(p_bukti_hash, 128), v_jenis.harga, 'menunggu', v_iphash)
  returning * into v_row;

  return json_build_object('kode', v_row.kode, 'status', v_row.status, 'harga', v_row.harga,
                           'created_at', v_row.created_at, 'no_wa', v_row.no_wa,
                           'jenis', v_row.jenis, 'seri_id', v_row.seri_id, 'nama_sekha', v_row.nama_sekha);
exception
  when unique_violation then
    if p_client_ref is not null then
      select * into v_row from public.lomba_pendaftaran where client_ref = p_client_ref;
      if found then
        return json_build_object('kode', v_row.kode, 'status', v_row.status, 'harga', v_row.harga,
                                 'created_at', v_row.created_at, 'no_wa', v_row.no_wa,
                                 'jenis', v_row.jenis, 'seri_id', v_row.seri_id, 'nama_sekha', v_row.nama_sekha);
      end if;
    end if;
    raise exception 'BUKTI_TIDAK_VALID';
end;
$$;

-- Cek status pendaftaran berdasarkan nomor WA (data terbatas)
create or replace function public.lomba_cek_status(p_no_wa text)
returns json
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_wa text := public.lomba_normalisasi_wa(p_no_wa);
begin
  if v_wa is null then
    raise exception 'WA_TIDAK_VALID';
  end if;
  return coalesce((
    select json_agg(x order by x.created_at desc)
    from (
      select p.kode, p.jenis, j.nama as jenis_nama, p.nama_sekha, p.status,
             p.nomor_layangan, p.alasan_tolak, p.harga, p.created_at,
             s.nama as seri_nama, s.tanggal, s.jam_mulai, s.jam_selesai
      from public.lomba_pendaftaran p
      join public.lomba_jenis j on j.kode = p.jenis
      join public.lomba_seri s on s.id = p.seri_id
      where p.no_wa = v_wa
      order by p.created_at desc
      limit 50
    ) x
  ), '[]'::json);
end;
$$;


