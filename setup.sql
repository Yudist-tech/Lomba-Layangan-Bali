-- Pemeriksaan kesehatan setup (dipakai menu Pengaturan di dashboard)
create or replace function public.lomba_cek_setup()
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_bucket boolean;
  v_media  boolean;
  v_pol    int;
  v_rt     boolean;
  v_admin  int;
begin
  if not public.lomba_is_admin() then
    raise exception 'BUKAN_ADMIN';
  end if;
  begin
    select exists (select 1 from storage.buckets where id = 'lomba-bukti') into v_bucket;
  exception when others then
    v_bucket := null;
  end;
  begin
    select exists (select 1 from storage.buckets where id = 'lomba-media') into v_media;
  exception when others then
    v_media := null;
  end;
  select count(*) into v_pol from pg_policies
   where schemaname = 'storage' and tablename = 'objects' and policyname like 'lomba_bukti_%';
  select exists (select 1 from pg_publication_tables
                  where pubname = 'supabase_realtime' and schemaname = 'public'
                    and tablename = 'lomba_pendaftaran') into v_rt;
  select count(*) into v_admin from public.lomba_admin;
  return json_build_object('bucket', v_bucket, 'media', v_media, 'storage_policies', v_pol,
                           'realtime', v_rt, 'admins', v_admin, 'versi', '1.0');
end;
$$;

-- Hapus semua pendaftaran & reset nomor urut (dipakai setelah uji coba).
-- Mengembalikan daftar file bukti agar dashboard ikut menghapusnya dari Storage.
create or replace function public.lomba_reset_data()
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_paths json;
  v_n     int;
begin
  if not public.lomba_is_admin() then
    raise exception 'BUKAN_ADMIN';
  end if;
  select coalesce(json_agg(bukti_path), '[]'::json) into v_paths
    from public.lomba_pendaftaran where bukti_path is not null;
  delete from public.lomba_pendaftaran where id is not null;
  get diagnostics v_n = row_count;
  update public.lomba_jenis set nomor_terakhir = 0 where kode is not null;
  return json_build_object('dihapus', v_n, 'bukti_paths', v_paths);
end;
$$;


