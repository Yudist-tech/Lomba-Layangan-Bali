-- Pengaturan event (hanya 1 baris, id = 1)
create table if not exists public.lomba_pengaturan (
  id                      int primary key default 1 check (id = 1),
  nama_event              text not null default 'Lomba Layangan Tradisional',
  penyelenggara           text not null default 'Panitia Lomba Layangan',
  lokasi                  text not null default '',
  info                    text not null default '',
  wa_admin                text not null default '',
  bank_nama               text not null default '',
  bank_no_rek             text not null default '',
  bank_atas_nama          text not null default '',
  pendaftaran_buka        boolean not null default true,
  batas_daftar            timestamptz,
  tampilkan_peserta       boolean not null default false,
  template_wa_konfirmasi  text not null default '',
  template_wa_tolak       text not null default '',
  updated_at              timestamptz not null default now()
);

-- Jenis layangan + harga + awalan nomor layangan
create table if not exists public.lomba_jenis (
  kode            text primary key,
  nama            text not null,
  harga           integer not null check (harga >= 0),
  prefix          text not null,
  urutan          int not null default 0,
  aktif           boolean not null default true,
  nomor_terakhir  int not null default 0 check (nomor_terakhir >= 0)
);

-- Seri = jadwal terbang, khusus per jenis layangan, kuota default 60
create table if not exists public.lomba_seri (
  id           bigint generated by default as identity primary key,
  jenis        text not null references public.lomba_jenis(kode) on update cascade,
  nama         text not null,
  tanggal      date,
  jam_mulai    time,
  jam_selesai  time,
  kuota        int not null default 60 check (kuota >= 0),
  aktif        boolean not null default true,
  catatan      text not null default '',
  urutan       int not null default 0,
  created_at   timestamptz not null default now()
);
create index if not exists lomba_seri_jenis_idx on public.lomba_seri (jenis);

-- Tampilan halaman peserta: logo & gambar latar (diatur admin di Pengaturan)
alter table public.lomba_pengaturan add column if not exists logo_url text not null default '';
alter table public.lomba_pengaturan add column if not exists bg_url   text not null default '';

-- Pendaftaran: 1 baris = 1 layangan
create table if not exists public.lomba_pendaftaran (
  id               uuid primary key default gen_random_uuid(),
  kode             text not null unique default public.lomba_kode_baru(),
  client_ref       uuid unique,
  jenis            text not null references public.lomba_jenis(kode) on update cascade,
  seri_id          bigint not null references public.lomba_seri(id),
  nama_sekha       text not null,
  alamat           text not null,
  no_wa            text not null,
  nama_rekening    text not null,
  bukti_path       text,
  bukti_hash       text,
  harga            integer not null,
  status           text not null default 'menunggu'
                   check (status in ('menunggu', 'terkonfirmasi', 'ditolak')),
  nomor_urut       int,
  nomor_layangan   text unique,
  alasan_tolak     text,
  catatan_admin    text not null default '',
  wa_terkirim_at   timestamptz,
  dikonfirmasi_at  timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists lomba_pendaftaran_seri_status_idx on public.lomba_pendaftaran (seri_id, status);
create index if not exists lomba_pendaftaran_wa_idx on public.lomba_pendaftaran (no_wa);
create index if not exists lomba_pendaftaran_created_idx on public.lomba_pendaftaran (created_at desc);
create index if not exists lomba_pendaftaran_hash_idx on public.lomba_pendaftaran (bukti_hash) where bukti_hash is not null;
create unique index if not exists lomba_pendaftaran_bukti_uidx on public.lomba_pendaftaran (bukti_path) where bukti_path is not null;
alter table public.lomba_pendaftaran add column if not exists ip_hash text;
create index if not exists lomba_pendaftaran_ip_idx on public.lomba_pendaftaran (ip_hash, created_at) where ip_hash is not null;


