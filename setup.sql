-- Pendaftaran: 1 baris = 1 layangan
create table if not exists public.lomba_pendaftaran (
  id               uuid primary key default gen_random_uuid(),
  kode             text not null unique default public.lomba_kode_baru(),
  client_ref       uuid unique,
  jenis            text not null references public.lomba_jenis(kode) on update cascade,
  seri_id          bigint not null references public.lomba_seri(id),
  nama_sekha       text not null,
  alamat           text not null,
  no_wa            text not null,
  nama_rekening    text not null,
  bukti_path       text,
  bukti_hash       text,
  harga            integer not null,
  status           text not null default 'menunggu'
                   check (status in ('menunggu', 'terkonfirmasi', 'ditolak')),
  nomor_urut       int,
  nomor_layangan   text unique,
  alasan_tolak     text,
  catatan_admin    text not null default '',
  wa_terkirim_at   timestamptz,
  dikonfirmasi_at  timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists lomba_pendaftaran_seri_status_idx on public.lomba_pendaftaran (seri_id, status);
create index if not exists lomba_pendaftaran_wa_idx on public.lomba_pendaftaran (no_wa);
create index if not exists lomba_pendaftaran_created_idx on public.lomba_pendaftaran (created_at desc);
create index if not exists lomba_pendaftaran_hash_idx on public.lomba_pendaftaran (bukti_hash) where bukti_hash is not null;
create unique index if not exists lomba_pendaftaran_bukti_uidx on public.lomba_pendaftaran (bukti_path) where bukti_path is not null;
alter table public.lomba_pendaftaran add column if not exists ip_hash text;
create index if not exists lomba_pendaftaran_ip_idx on public.lomba_pendaftaran (ip_hash, created_at) where ip_hash is not null;

