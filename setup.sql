-- Jenis layangan + harga + awalan nomor layangan
create table if not exists public.lomba_jenis (
  kode            text primary key,
  nama            text not null,
  harga           integer not null check (harga >= 0),
  prefix          text not null,
  urutan          int not null default 0,
  aktif           boolean not null default true,
  nomor_terakhir  int not null default 0 check (nomor_terakhir >= 0)
);

-- Seri = jadwal terbang, khusus per jenis layangan, kuota default 60
create table if not exists public.lomba_seri (
  id           bigint generated by default as identity primary key,
  jenis        text not null references public.lomba_jenis(kode) on update cascade,
  nama         text not null,
  tanggal      date,
  jam_mulai    time,
  jam_selesai  time,
  kuota        int not null default 60 check (kuota >= 0),
  aktif        boolean not null default true,
  catatan      text not null default '',
  urutan       int not null default 0,
  created_at   timestamptz not null default now()
);
create index if not exists lomba_seri_jenis_idx on public.lomba_seri (jenis);

-- ---------------------------------------------------------------------
-- JADWAL TERBANG (v2): Hari → Seri (blok waktu, mis. Seri I 09.30–10.30)
--                      → Grup A, B, C… (1 jenis layangan, mis. 50 kotak)
--   · Tabel lomba_seri di atas dipakai sebagai GRUP: 1 baris = 1 grup
--     (jenis + jumlah kotak + kotak yang ditutup panitia).
--   · Tanggal, jam, dan nama grup ("Seri I · A") diisi otomatis dari
--     hari & seri, jadi tampilan lama (WA, cek status, ekspor) tetap jalan.
--   · Grup tanpa sesi_id = seri lama (sebelum jadwal terbang).
-- ---------------------------------------------------------------------
create table if not exists public.lomba_hari (
  id          bigint generated by default as identity primary key,
  nama        text not null,
  tanggal     date,
  urutan      int not null default 0,
  created_at  timestamptz not null default now()
);

-- "Seri" pada tabel jadwal (I, II, III…) = blok waktu terbang dalam 1 hari
create table if not exists public.lomba_sesi (
  id           bigint generated by default as identity primary key,
  hari_id      bigint not null references public.lomba_hari(id) on delete restrict,
  nama         text not null,
  jam_mulai    time,
  jam_selesai  time,
  urutan       int not null default 0,
  created_at   timestamptz not null default now()
);
create index if not exists lomba_sesi_hari_idx on public.lomba_sesi (hari_id);

