create or replace function public.lomba_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.lomba_admin a
    join auth.users u on lower(u.email) = lower(a.email)
    where u.id = auth.uid()
      and u.email_confirmed_at is not null
  );
$$;


-- ---------------------------------------------------------------------
-- BAGIAN 4 · ATURAN OTOMATIS (TRIGGER)
--   · kuota seri dijaga di database (aman walau banyak yang daftar bersamaan)
--   · nomor layangan otomatis per jenis saat status → terkonfirmasi (BB-001, …)
--   · tanda "WA terkirim" direset bila data penting berubah
-- ---------------------------------------------------------------------
create or replace function public.lomba_trg_pendaftaran()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_seri    public.lomba_seri%rowtype;
  v_terisi  int;
  v_cek     boolean;
  v_k       int;
begin
  -- 1) rapikan & validasi data dasar
  new.nama_sekha    := btrim(coalesce(new.nama_sekha, ''));
  new.alamat        := btrim(coalesce(new.alamat, ''));
  new.nama_rekening := btrim(coalesce(new.nama_rekening, ''));
  new.no_wa         := public.lomba_normalisasi_wa(new.no_wa);
  if new.no_wa is null then
    raise exception 'WA_TIDAK_VALID';
  end if;
  if new.nama_sekha = '' or new.alamat = '' or new.nama_rekening = '' then
    raise exception 'DATA_TIDAK_LENGKAP';
  end if;

  -- 2) jenis diganti → harga mengikuti jenis baru
  if tg_op = 'UPDATE' and new.jenis is distinct from old.jenis then
    new.harga := null;
  end if;
  -- pindah grup → posisi kotak dipilih ulang
  if tg_op = 'UPDATE' and new.seri_id is distinct from old.seri_id
     and new.kotak is not distinct from old.kotak then
    new.kotak := null;
  end if;
  if new.harga is null then
    select j.harga into new.harga from public.lomba_jenis j where j.kode = new.jenis;
  end if;

  -- 3) seri harus sesuai jenis + cek kuota (baris seri dikunci agar antre)
  v_cek := new.status in ('menunggu', 'terkonfirmasi')
           and (tg_op = 'INSERT'
                or new.seri_id is distinct from old.seri_id
                or old.status = 'ditolak'
                or new.kotak is null
                or new.kotak is distinct from old.kotak);
  if v_cek then
    select * into v_seri from public.lomba_seri where id = new.seri_id for update;
  else
    select * into v_seri from public.lomba_seri where id = new.seri_id;
  end if;
  if not found then
    raise exception 'SERI_TIDAK_VALID';
  end if;
  if v_seri.jenis <> new.jenis then
    raise exception 'SERI_TIDAK_SESUAI_JENIS';
  end if;
  if v_cek then
    select count(*) into v_terisi
    from public.lomba_pendaftaran
    where seri_id = new.seri_id
      and status in ('menunggu', 'terkonfirmasi')
      and id <> new.id;
    if (tg_op = 'INSERT' or new.seri_id is distinct from old.seri_id or old.status = 'ditolak')
       and v_terisi >= v_seri.kuota then
      raise exception 'KUOTA_PENUH';
    end if;
  end if;

  -- 3b) posisi kotak di tabel jadwal (hanya grup jadwal terbang)
  if new.status not in ('menunggu', 'terkonfirmasi') or v_seri.sesi_id is null then
    new.kotak := null;
  elsif v_cek then
    if new.kotak is not null and (
         new.kotak < 1 or new.kotak > v_seri.kotak
         or new.kotak = any(v_seri.tutup)
         or exists (select 1 from public.lomba_pendaftaran p
                     where p.seri_id = new.seri_id and p.kotak = new.kotak
                       and p.status in ('menunggu', 'terkonfirmasi') and p.id <> new.id)) then
      new.kotak := null;
    end if;
    if new.kotak is null then
      select min(k) into v_k
        from generate_series(1, v_seri.kotak) k
       where not (k = any(v_seri.tutup))
         and not exists (select 1 from public.lomba_pendaftaran p
                          where p.seri_id = new.seri_id and p.kotak = k
                            and p.status in ('menunggu', 'terkonfirmasi') and p.id <> new.id);
      if v_k is null then
        raise exception 'KUOTA_PENUH';
      end if;
      new.kotak := v_k;
    end if;
  end if;

  -- 4) nomor layangan: diisi peserta, unik per jenis (angka → tanpa nol di depan)
  if new.nomor_layangan is not null then
    new.nomor_layangan := nullif(upper(btrim(new.nomor_layangan)), '');
    if new.nomor_layangan ~ '^[0-9]+$' then
      new.nomor_layangan := coalesce(nullif(ltrim(new.nomor_layangan, '0'), ''), '0');
    end if;
  end if;
  if tg_op = 'INSERT' or new.nomor_layangan is distinct from old.nomor_layangan then
    new.nomor_urut := nullif(left(regexp_replace(coalesce(new.nomor_layangan, ''), '\D', '', 'g'), 9), '')::int;
  end if;
  if new.nomor_layangan is not null and new.status in ('menunggu', 'terkonfirmasi')
     and exists (select 1 from public.lomba_pendaftaran p
                  where p.jenis = new.jenis and p.nomor_layangan = new.nomor_layangan
                    and p.status in ('menunggu', 'terkonfirmasi') and p.id <> new.id) then
    raise exception 'NOMOR_DIPAKAI';
  end if;

  -- 5) jejak waktu & alasan
  if new.status = 'terkonfirmasi' then
    if tg_op = 'INSERT' or old.status is distinct from 'terkonfirmasi' then
      new.dikonfirmasi_at := now();
    end if;
  else
    new.dikonfirmasi_at := null;
  end if;
  if new.status <> 'ditolak' then
    new.alasan_tolak := null;
  end if;

  -- 6) data penting berubah → WA perlu dikirim ulang
  if tg_op = 'UPDATE'
     and new.wa_terkirim_at is not distinct from old.wa_terkirim_at
     and (new.status is distinct from old.status
          or new.seri_id is distinct from old.seri_id
          or new.jenis is distinct from old.jenis
          or new.nomor_layangan is distinct from old.nomor_layangan
          or new.kotak is distinct from old.kotak
          or new.no_wa is distinct from old.no_wa) then
    new.wa_terkirim_at := null;
  end if;

  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists lomba_pendaftaran_biu on public.lomba_pendaftaran;
create trigger lomba_pendaftaran_biu
  before insert or update on public.lomba_pendaftaran
  for each row execute function public.lomba_trg_pendaftaran();

create or replace function public.lomba_trg_seri()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_sesi  text;
  v_mulai time;
  v_akhir time;
  v_tgl   date;
begin
  -- grup jadwal terbang: nama, tanggal, jam & kuota dihitung otomatis
  if new.sesi_id is not null then
    select s.nama, s.jam_mulai, s.jam_selesai, h.tanggal
      into v_sesi, v_mulai, v_akhir, v_tgl
      from public.lomba_sesi s join public.lomba_hari h on h.id = s.hari_id
     where s.id = new.sesi_id;
    if not found then
      raise exception 'SERI_TIDAK_VALID';
    end if;
    new.huruf := upper(btrim(coalesce(new.huruf, '')));
    if new.huruf = '' then
      raise exception 'DATA_TIDAK_LENGKAP';
    end if;
    new.nama        := 'Seri ' || v_sesi || ' · ' || new.huruf;
    new.tanggal     := v_tgl;
    new.jam_mulai   := v_mulai;
    new.jam_selesai := v_akhir;
    new.tutup := coalesce((select array_agg(distinct x order by x)
                             from unnest(new.tutup) x where x between 1 and new.kotak), '{}');
    new.kuota := greatest(0, new.kotak - cardinality(new.tutup));
    if tg_op = 'UPDATE'
       and (new.kotak is distinct from old.kotak or new.tutup is distinct from old.tutup)
       and exists (
         select 1 from public.lomba_pendaftaran p
          where p.seri_id = new.id and p.kotak is not null
            and p.status in ('menunggu', 'terkonfirmasi')
            and (p.kotak > new.kotak or p.kotak = any(new.tutup))) then
      raise exception 'KOTAK_TERISI';
    end if;
  end if;

  new.nama := btrim(coalesce(new.nama, ''));
  if new.nama = '' then
    raise exception 'DATA_TIDAK_LENGKAP';
  end if;
  if tg_op = 'UPDATE' and new.jenis is distinct from old.jenis
     and exists (select 1 from public.lomba_pendaftaran where seri_id = old.id) then
    raise exception 'SERI_ADA_PESERTA';
  end if;
  return new;
end;
$$;

drop trigger if exists lomba_seri_biu on public.lomba_seri;
create trigger lomba_seri_biu
  before insert or update on public.lomba_seri
  for each row execute function public.lomba_trg_seri();

