$$;

create or replace function public.lomba_trg_sesi_setelah()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_table_name = 'lomba_hari' then
    update public.lomba_seri g set sesi_id = g.sesi_id
      from public.lomba_sesi s where s.id = g.sesi_id and s.hari_id = new.id;
  else
    update public.lomba_seri set sesi_id = sesi_id where sesi_id = new.id;
  end if;
  return null;
end;
$$;

