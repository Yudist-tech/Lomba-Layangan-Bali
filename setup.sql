-- Nomor WA → format 62xxxxxxxxxx (08.. → 628.., 8.. → 628..). Null jika tidak valid.
create or replace function public.lomba_normalisasi_wa(p text)
returns text
language plpgsql
immutable
set search_path = public
as $$
declare
  d text := regexp_replace(coalesce(p, ''), '\D', '', 'g');
begin
  if d like '0%' then
    d := '62' || substr(d, 2);
  elsif d like '8%' then
    d := '62' || d;
  end if;
  if d like '620%' then
    d := '62' || substr(d, 4);   -- '+62 0812…' → '62812…'
  end if;
  if d ~ '^[1-9][0-9]{9,14}$' then
    return d;
  end if;
  return null;
end;
$$;

-- Kode pendaftaran acak & unik, contoh: LL-7K3Q9P (tanpa huruf/angka yang mirip)
create or replace function public.lomba_kode_baru()
returns text
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  abc constant text := '23456789ABCDEFGHJKLMNPQRSTUVWXYZ';
  v text;
begin
  loop
    v := 'LL-';
    for i in 1..6 loop
      v := v || substr(abc, 1 + floor(random() * 32)::int, 1);
    end loop;
    exit when not exists (select 1 from public.lomba_pendaftaran where kode = v);
  end loop;
  return v;
end;
$$;


