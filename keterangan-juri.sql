-- =====================================================================
-- KETERANGAN SINGKAT JURI NILAI (versi 1.0)
-- Jalankan SETELAH juara.sql dan upload-form.sql. Aman dijalankan ulang.
--
-- Kolom "Keterangan singkat" di form juri nilai: saat form di-upload,
-- potongan tulisan juri disimpan per layangan per juri. Di tabel penilaian
-- nilai itu diberi tanda "!" — diklik untuk melihat tulisan aslinya,
-- dan panitia boleh mengetik ulang isinya (opsional).
-- Hanya untuk panitia (tidak tampil di halaman publik), tidak mengubah nilai.
-- Setiap tambah / ubah / hapus tercatat di Riwayat beserta ID panitia.
-- =====================================================================

create table if not exists public.lomba_ket_juri (
  id              bigint generated by default as identity primary key,
  event_id        bigint not null references public.lomba_event(id) on delete cascade,
  pendaftaran_id  uuid not null references public.lomba_pendaftaran(id) on delete cascade,
  juri_id         bigint not null references public.lomba_juri(id) on delete cascade,
  teks            text not null default '',            -- diketik panitia (opsional)
  foto_url        text check (foto_url is null or (foto_url like 'data:image/%' and length(foto_url) < 400000)),
  upload_id       bigint references public.lomba_form_upload(id) on delete set null,
  baris           int,
  oleh            text,
  updated_at      timestamptz not null default now(),
  unique (pendaftaran_id, juri_id)
);
create index if not exists lomba_ket_juri_event_idx on public.lomba_ket_juri (event_id);

alter table public.lomba_ket_juri enable row level security;
drop policy if exists lomba_baca on public.lomba_ket_juri;
drop policy if exists lomba_menilai_tambah on public.lomba_ket_juri;
drop policy if exists lomba_menilai_ubah on public.lomba_ket_juri;
drop policy if exists lomba_menilai_hapus on public.lomba_ket_juri;
create policy lomba_baca on public.lomba_ket_juri for select to authenticated using ((select public.lomba_boleh_event(event_id)));
create policy lomba_menilai_tambah on public.lomba_ket_juri for insert to authenticated with check ((select public.lomba_boleh_menilai(event_id)));
create policy lomba_menilai_ubah on public.lomba_ket_juri for update to authenticated using ((select public.lomba_boleh_menilai(event_id))) with check ((select public.lomba_boleh_menilai(event_id)));
create policy lomba_menilai_hapus on public.lomba_ket_juri for delete to authenticated using ((select public.lomba_boleh_menilai(event_id)));
revoke all on table public.lomba_ket_juri from anon;
grant select, insert, update, delete on table public.lomba_ket_juri to authenticated;

-- layangan & juri harus milik event yang sama; "oleh" & waktu diisi database
create or replace function public.lomba_trg_ket_juri()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (select 1 from public.lomba_pendaftaran where id = new.pendaftaran_id and event_id = new.event_id)
     or not exists (select 1 from public.lomba_juri where id = new.juri_id and event_id = new.event_id) then
    raise exception 'JUARA_TIDAK_VALID';
  end if;
  new.teks := left(btrim(coalesce(new.teks, '')), 300);
  new.oleh := public.lomba_email_saya();
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists lomba_ket_juri_biu on public.lomba_ket_juri;
create trigger lomba_ket_juri_biu before insert or update on public.lomba_ket_juri
  for each row execute function public.lomba_trg_ket_juri();

-- riwayat: tambah / ubah / hapus keterangan juri
create or replace function public.lomba_trg_riwayat_ket_juri()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  r record; p record; v_juri text; v_ket text;
  lama text := case when tg_op = 'INSERT' then null else coalesce(nullif(old.teks, ''), '(tulisan tangan)') end;
  baru text := case when tg_op = 'DELETE' then null else coalesce(nullif(new.teks, ''), '(tulisan tangan)') end;
begin
  r := coalesce(new, old);
  if tg_op = 'UPDATE' and lama is not distinct from baru and new.foto_url is not distinct from old.foto_url then return null; end if;
  select event_id, jenis, nomor_layangan into p from public.lomba_pendaftaran where id = r.pendaftaran_id;
  if p.event_id is null then return null; end if;
  select coalesce(nullif(btrim(nama), ''), 'Juri ' || urutan) into v_juri from public.lomba_juri where id = r.juri_id;
  v_ket := case tg_op when 'INSERT' then 'tambah: ' || baru
                      when 'UPDATE' then 'ubah: ' || lama || ' → ' || baru
                      else 'hapus: ' || lama end;
  perform public.lomba_catat_nilai(p.event_id, p.jenis, p.nomor_layangan, 'ket_juri', coalesce(v_juri, 'Juri'), null, null, left(v_ket, 400));
  return null;
end;
$$;
drop trigger if exists lomba_riwayat_ket_juri_aiud on public.lomba_ket_juri;
create trigger lomba_riwayat_ket_juri_aiud after insert or update or delete on public.lomba_ket_juri
  for each row execute function public.lomba_trg_riwayat_ket_juri();

revoke all on function public.lomba_trg_ket_juri() from public, anon, authenticated;
revoke all on function public.lomba_trg_riwayat_ket_juri() from public, anon, authenticated;

-- Pemeriksaan
select '✅ Tabel keterangan juri siap' as hasil
where exists (select 1 from information_schema.tables where table_schema = 'public' and table_name = 'lomba_ket_juri')
union all
select '✅ Riwayat keterangan juri aktif'
where exists (select 1 from pg_trigger where tgname = 'lomba_riwayat_ket_juri_aiud');
