-- =====================================================================
-- RIWAYAT & PENCATATAN PANITIA (versi 1.0)
-- Jalankan SETELAH multi-event.sql (dan login-id.sql / login-nama.sql bila dipakai).
-- Aman dijalankan ulang (idempotent). Tidak mengubah data yang sudah ada.
--
-- Database mencatat OTOMATIS siapa (akun yang sedang login) yang:
--   mengonfirmasi, menolak, mengirim WA, mengubah, menambah, atau menghapus pendaftaran.
-- Catatan dibuat oleh database, sehingga tidak bisa dipalsukan / dihapus dari aplikasi.
-- =====================================================================

-- 1) kolom "oleh" di pendaftaran (diisi otomatis, tidak bisa diisi dari aplikasi)
alter table public.lomba_pendaftaran add column if not exists dikonfirmasi_oleh text;
alter table public.lomba_pendaftaran add column if not exists ditolak_oleh text;
alter table public.lomba_pendaftaran add column if not exists ditolak_at timestamptz;
alter table public.lomba_pendaftaran add column if not exists wa_oleh text;

-- 2) tabel riwayat
create table if not exists public.lomba_riwayat (
  id             bigint generated by default as identity primary key,
  event_id       bigint not null references public.lomba_event(id) on delete cascade,
  pendaftaran_id uuid,                -- sengaja tanpa foreign key: riwayat tetap ada walau pendaftaran dihapus
  kode           text,
  aksi           text not null,       -- daftar, tambah, konfirmasi, tolak, menunggu, wa, ubah, hapus
  detail         jsonb not null default '{}'::jsonb,
  oleh           text,                -- email/ID akun; kosong = peserta (formulir pendaftaran)
  created_at     timestamptz not null default now()
);
create index if not exists lomba_riwayat_pendaftaran_idx on public.lomba_riwayat (pendaftaran_id, created_at);
create index if not exists lomba_riwayat_event_idx on public.lomba_riwayat (event_id, created_at desc);

alter table public.lomba_riwayat enable row level security;
drop policy if exists lomba_riwayat_baca on public.lomba_riwayat;
create policy lomba_riwayat_baca on public.lomba_riwayat for select to authenticated
  using ((select public.lomba_boleh_event(event_id)));
revoke all on table public.lomba_riwayat from anon;
revoke insert, update, delete on table public.lomba_riwayat from authenticated;
grant select on table public.lomba_riwayat to authenticated;

-- 3) BEFORE: isi kolom "oleh" berdasarkan akun yang login (jalan setelah trigger utama)
create or replace function public.lomba_trg_pendaftaran_oleh()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_saya text := public.lomba_email_saya();
begin
  if tg_op = 'INSERT' then
    new.dikonfirmasi_oleh := case when new.status = 'terkonfirmasi' then v_saya end;
    new.ditolak_oleh      := case when new.status = 'ditolak' then v_saya end;
    new.ditolak_at        := case when new.status = 'ditolak' then now() end;
    new.wa_oleh           := case when new.wa_terkirim_at is not null then v_saya end;
    return new;
  end if;
  -- nilai lama dipertahankan; aplikasi tidak bisa menulis kolom ini sendiri
  new.dikonfirmasi_oleh := old.dikonfirmasi_oleh;
  new.ditolak_oleh      := old.ditolak_oleh;
  new.ditolak_at        := old.ditolak_at;
  new.wa_oleh           := old.wa_oleh;
  if new.status is distinct from old.status then
    if new.status = 'terkonfirmasi' then new.dikonfirmasi_oleh := v_saya; end if;
    if new.status = 'ditolak' then new.ditolak_oleh := v_saya; new.ditolak_at := now(); end if;
    if new.status <> 'terkonfirmasi' then new.dikonfirmasi_oleh := null; end if;
    if new.status <> 'ditolak' then new.ditolak_oleh := null; new.ditolak_at := null; end if;
  end if;
  if new.wa_terkirim_at is null then
    new.wa_oleh := null;
  elsif new.wa_terkirim_at is distinct from old.wa_terkirim_at then
    new.wa_oleh := v_saya;
  end if;
  return new;
end;
$$;

drop trigger if exists lomba_pendaftaran_oleh_bu on public.lomba_pendaftaran;
create trigger lomba_pendaftaran_oleh_bu
  before insert or update on public.lomba_pendaftaran
  for each row execute function public.lomba_trg_pendaftaran_oleh();

-- 4) AFTER: tulis riwayat
create or replace function public.lomba_trg_pendaftaran_riwayat()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_saya  text := public.lomba_email_saya();
  v_ubah  jsonb := '{}'::jsonb;
  v_kol   text;
  v_lama  jsonb;
  v_baru  jsonb;
begin
  if tg_op = 'INSERT' then
    insert into public.lomba_riwayat (event_id, pendaftaran_id, kode, aksi, detail, oleh)
    values (new.event_id, new.id, new.kode, case when v_saya is null then 'daftar' else 'tambah' end,
            jsonb_build_object('status', new.status, 'nomor', new.nomor_layangan, 'jenis', new.jenis), v_saya);
    if new.status = 'terkonfirmasi' and v_saya is not null then
      insert into public.lomba_riwayat (event_id, pendaftaran_id, kode, aksi, oleh) values (new.event_id, new.id, new.kode, 'konfirmasi', v_saya);
    end if;
    return null;
  end if;

  if tg_op = 'DELETE' then
    if not exists (select 1 from public.lomba_event where id = old.event_id) then
      return null;   -- event ikut dihapus: riwayatnya juga hilang
    end if;
    insert into public.lomba_riwayat (event_id, pendaftaran_id, kode, aksi, detail, oleh)
    values (old.event_id, old.id, old.kode, 'hapus',
            jsonb_build_object('sekha', old.nama_sekha, 'nomor', old.nomor_layangan, 'status', old.status), v_saya);
    return null;
  end if;

  -- UPDATE: status
  if new.status is distinct from old.status then
    insert into public.lomba_riwayat (event_id, pendaftaran_id, kode, aksi, detail, oleh)
    values (new.event_id, new.id, new.kode,
            case new.status when 'terkonfirmasi' then 'konfirmasi' when 'ditolak' then 'tolak' else 'menunggu' end,
            case when new.status = 'ditolak' then jsonb_build_object('alasan', new.alasan_tolak) else '{}'::jsonb end,
            v_saya);
  end if;
  -- WA ditandai terkirim
  if new.wa_terkirim_at is not null and new.wa_terkirim_at is distinct from old.wa_terkirim_at then
    insert into public.lomba_riwayat (event_id, pendaftaran_id, kode, aksi, detail, oleh)
    values (new.event_id, new.id, new.kode, 'wa', jsonb_build_object('jenis', case when new.status = 'ditolak' then 'penolakan' else 'konfirmasi' end), v_saya);
  end if;
  -- perubahan data (nomor yang hanya berubah format nol di depan tidak dicatat)
  v_lama := to_jsonb(old); v_baru := to_jsonb(new);
  foreach v_kol in array array['nama_sekha', 'alamat', 'no_wa', 'nama_rekening', 'jenis', 'seri_id', 'kotak', 'nomor_layangan', 'harga', 'catatan_admin'] loop
    if v_lama -> v_kol is distinct from v_baru -> v_kol then
      if v_kol = 'nomor_layangan' and ltrim(coalesce(old.nomor_layangan, ''), '0') = ltrim(coalesce(new.nomor_layangan, ''), '0') then
        continue;
      end if;
      if v_kol in ('kotak', 'harga') and new.status is distinct from old.status then
        continue;   -- kotak dilepas / harga ikut berubah karena status: bukan perubahan oleh panitia
      end if;
      v_ubah := v_ubah || jsonb_build_object(v_kol, jsonb_build_array(v_lama -> v_kol, v_baru -> v_kol));
    end if;
  end loop;
  if v_ubah <> '{}'::jsonb and v_saya is not null then
    insert into public.lomba_riwayat (event_id, pendaftaran_id, kode, aksi, detail, oleh)
    values (new.event_id, new.id, new.kode, 'ubah', v_ubah, v_saya);
  end if;
  return null;
end;
$$;

drop trigger if exists lomba_pendaftaran_riwayat_aiud on public.lomba_pendaftaran;
create trigger lomba_pendaftaran_riwayat_aiud
  after insert or update or delete on public.lomba_pendaftaran
  for each row execute function public.lomba_trg_pendaftaran_riwayat();

-- 5) nama lengkap panitia: panitia juga bisa melihat nama rekan di event yang sama
do $$
begin
  if to_regclass('public.lomba_panitia') is not null then
    execute $f$
      create or replace function public.lomba_nama_panitia()
      returns json
      language plpgsql
      stable
      security definer
      set search_path = public
      as $b$
      begin
        if public.lomba_is_super() then
          return coalesce((select json_object_agg(email, nama) from public.lomba_panitia), '{}'::json);
        end if;
        return coalesce((
          select json_object_agg(p.email, p.nama) from public.lomba_panitia p
           where p.email = public.lomba_email_saya()
              or exists (select 1 from public.lomba_event_admin a
                          where a.email = p.email and public.lomba_boleh_event(a.event_id))), '{}'::json);
      end;
      $b$;
    $f$;
  end if;
end $$;

revoke all on function public.lomba_trg_pendaftaran_oleh() from public, anon, authenticated;
revoke all on function public.lomba_trg_pendaftaran_riwayat() from public, anon, authenticated;

-- Pemeriksaan
select '✅ Kolom pencatat panitia siap' as hasil
where exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'lomba_pendaftaran' and column_name = 'wa_oleh')
union all
select '✅ Tabel riwayat siap'
where exists (select 1 from information_schema.tables where table_schema = 'public' and table_name = 'lomba_riwayat')
union all
select '✅ Pencatatan otomatis aktif'
where exists (select 1 from pg_trigger where tgname = 'lomba_pendaftaran_riwayat_aiud');
