-- email akun yang sedang login (hanya yang sudah terkonfirmasi)
create or replace function public.lomba_email_saya()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select lower(u.email) from auth.users u
   where u.id = auth.uid() and u.email_confirmed_at is not null;
$$;

-- super admin = email di tabel lomba_admin
create or replace function public.lomba_is_super()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.lomba_admin a where lower(a.email) = public.lomba_email_saya());
$$;

-- boleh mengelola event ini? (super admin, atau admin yang ditugaskan)
create or replace function public.lomba_boleh_event(p_event bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.lomba_is_super()
      or exists (select 1 from public.lomba_event_admin ea
                  where ea.event_id = p_event and ea.email = public.lomba_email_saya());
$$;

-- admin event mana pun (dipakai untuk akses gambar & cek login)
create or replace function public.lomba_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.lomba_is_super()
      or exists (select 1 from public.lomba_event_admin ea where ea.email = public.lomba_email_saya());
$$;

create or replace function public.lomba_peran()
returns json
language sql
stable
security definer
set search_path = public
as $$
  select case when public.lomba_email_saya() is null then null
    else json_build_object('email', public.lomba_email_saya(),
                           'peran', case when public.lomba_is_super() then 'super' else 'panitia' end) end;
$$;


