create table if not exists public.lomba_event (
  id          bigint generated by default as identity primary key,
  slug        text not null unique,
  tampil      boolean not null default true,
  created_at  timestamptz not null default now()
);
do $$ begin
  alter table public.lomba_event add constraint lomba_event_slug_chk
    check (slug ~ '^[a-z0-9][a-z0-9-]{1,38}[a-z0-9]$' and slug not in ('admin', 'panitia', 'semua', 'tiket'));
exception when duplicate_object then null; end $$;

-- Email admin (panitia) per event. Super admin tetap di tabel lomba_admin.
create table if not exists public.lomba_event_admin (
  event_id    bigint not null references public.lomba_event(id),
  email       text not null check (email = lower(btrim(email)) and email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  created_at  timestamptz not null default now(),
  primary key (event_id, email)
);
create index if not exists lomba_event_admin_email_idx on public.lomba_event_admin (email);

-- Pengaturan situs = halaman depan semua event (hanya 1 baris)
create table if not exists public.lomba_situs (
  id          int primary key default 1 check (id = 1),
  nama        text not null default 'Lomba Layangan Bali',
  judul       text not null default 'Semua lomba layangan, satu tempat daftar.',
  teks        text not null default 'Pilih event, isi data layangan, transfer, dan unggah bukti. Nomor & jadwal terbang langsung terlihat.',
  logo_url    text not null default '',
  bg_url      text not null default '',
  updated_at  timestamptz not null default now()
);
insert into public.lomba_situs (id) values (1) on conflict (id) do nothing;

-- Event pertama = data yang sudah ada (kode alamat dari nama event)
do $$
declare
  v_nama text;
  v_slug text;
begin
  if exists (select 1 from public.lomba_event) then
    return;
  end if;
  select nama_event into v_nama from public.lomba_pengaturan order by id limit 1;
  v_slug := regexp_replace(lower(coalesce(v_nama, '')), '[^a-z0-9]+', '-', 'g');
  v_slug := regexp_replace(left(regexp_replace(v_slug, '^-+', ''), 40), '-+$', '');
  if v_slug is null or length(v_slug) < 3 or v_slug in ('admin', 'panitia', 'semua', 'tiket') then
    v_slug := 'event-pertama';
  end if;
  insert into public.lomba_event (slug) values (v_slug);
end $$;

-- Event bawaan untuk halaman/data lama yang belum menyebut event
create or replace function public.lomba_event_default()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select min(id) from public.lomba_event;
$$;


-- ---------------------------------------------------------------------
-- BAGIAN 2 · KOLOM event_id DI SEMUA TABEL LOMBA
-- ---------------------------------------------------------------------
do $$
declare
  t text;
begin
  foreach t in array array['lomba_pengaturan', 'lomba_jenis', 'lomba_hari', 'lomba_sesi', 'lomba_seri', 'lomba_pendaftaran']
  loop
    execute format('alter table public.%I add column if not exists event_id bigint default public.lomba_event_default()', t);
    execute format('update public.%I set event_id = public.lomba_event_default() where event_id is null', t);
    execute format('alter table public.%I alter column event_id set default public.lomba_event_default()', t);
    execute format('alter table public.%I alter column event_id set not null', t);
    begin
      execute format('alter table public.%I add constraint %I foreign key (event_id) references public.lomba_event(id)', t, t || '_event_fkey');
    exception when duplicate_object then null;
    end;
    execute format('create index if not exists %I on public.%I (event_id)', t || '_event_idx', t);
  end loop;
end $$;

-- Pengaturan: dulu hanya 1 baris (id = 1), sekarang 1 baris per event
alter table public.lomba_pengaturan drop constraint if exists lomba_pengaturan_id_check;
create sequence if not exists public.lomba_pengaturan_id_seq owned by public.lomba_pengaturan.id;
select setval('public.lomba_pengaturan_id_seq', greatest((select coalesce(max(id), 1) from public.lomba_pengaturan), 1));
alter table public.lomba_pengaturan alter column id set default nextval('public.lomba_pengaturan_id_seq');
create unique index if not exists lomba_pengaturan_event_uidx on public.lomba_pengaturan (event_id);
alter table public.lomba_pengaturan add column if not exists tanggal_mulai   date;
alter table public.lomba_pengaturan add column if not exists tanggal_selesai date;
-- flyer event (gambar A4 tegak) untuk halaman depan
alter table public.lomba_pengaturan add column if not exists flyer_url text not null default '';
-- tanggal event pertama diambil dari jadwal yang sudah ada
update public.lomba_pengaturan st
   set tanggal_mulai   = x.mulai,
       tanggal_selesai = x.akhir
  from (select h.event_id, min(h.tanggal) as mulai, max(h.tanggal) as akhir
          from public.lomba_hari h where h.tanggal is not null group by h.event_id) x
 where x.event_id = st.event_id and st.tanggal_mulai is null;

-- Jenis layangan: kode unik PER EVENT (dua event boleh punya jenis "bebean-plastik")
do $$
declare
  r record;
begin
  if exists (select 1 from pg_constraint
              where conrelid = 'public.lomba_jenis'::regclass and contype = 'p' and array_length(conkey, 1) = 2) then
    return;   -- sudah diubah
  end if;
  for r in select conname, conrelid::regclass as tbl from pg_constraint
            where confrelid = 'public.lomba_jenis'::regclass and contype = 'f'
  loop
    execute format('alter table %s drop constraint %I', r.tbl, r.conname);
  end loop;
  alter table public.lomba_jenis drop constraint lomba_jenis_pkey;
  alter table public.lomba_jenis add constraint lomba_jenis_pkey primary key (event_id, kode);
  alter table public.lomba_seri add constraint lomba_seri_jenis_fkey
    foreign key (event_id, jenis) references public.lomba_jenis(event_id, kode) on update cascade;
  alter table public.lomba_pendaftaran add constraint lomba_pendaftaran_jenis_fkey
    foreign key (event_id, jenis) references public.lomba_jenis(event_id, kode) on update cascade;
end $$;

-- Nomor layangan unik per JENIS di dalam EVENT yang sama
drop index if exists public.lomba_pendaftaran_nomor_uidx;
create unique index if not exists lomba_pendaftaran_nomor_ev_uidx
  on public.lomba_pendaftaran (event_id, jenis, nomor_layangan)
  where nomor_layangan is not null and status in ('menunggu', 'terkonfirmasi');


