-- buat event baru (opsional: salin jenis, rekening, pesan, tampilan dari event lain)
create or replace function public.lomba_buat_event(p jsonb)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_slug  text;
  v_id    bigint;
  v_src   bigint := nullif(p ->> 'salin_dari', '')::bigint;
  v_salin jsonb := coalesce(p -> 'salin', '{}'::jsonb);
  v_a     public.lomba_pengaturan%rowtype;
  v_email text;
  v_mulai date := nullif(p ->> 'tanggal_mulai', '')::date;
  v_akhir date := coalesce(nullif(p ->> 'tanggal_selesai', '')::date, nullif(p ->> 'tanggal_mulai', '')::date);
begin
  perform public.lomba_wajib_super();
  if btrim(coalesce(p ->> 'nama_event', '')) = '' then
    raise exception 'DATA_TIDAK_LENGKAP';
  end if;
  if v_mulai is not null and v_akhir < v_mulai then
    raise exception 'TANGGAL_TIDAK_VALID';
  end if;
  v_slug := public.lomba_cek_slug(p ->> 'slug');
  insert into public.lomba_event (slug, tampil) values (v_slug, coalesce((p ->> 'tampil')::boolean, true))
  returning id into v_id;

  if v_src is not null then
    select * into v_a from public.lomba_pengaturan where event_id = v_src;
  end if;
  insert into public.lomba_pengaturan
    (event_id, nama_event, penyelenggara, lokasi, tanggal_mulai, tanggal_selesai, pendaftaran_buka,
     info, wa_admin, bank_nama, bank_no_rek, bank_atas_nama, template_wa_konfirmasi, template_wa_tolak, logo_url, bg_url, flyer_url)
  values
    (v_id, btrim(p ->> 'nama_event'),
     coalesce(nullif(btrim(p ->> 'penyelenggara'), ''), 'Panitia Lomba Layangan'),
     coalesce(btrim(p ->> 'lokasi'), ''), v_mulai, v_akhir, false,
     case when (v_salin ->> 'pesan')::boolean then coalesce(v_a.info, '') else '' end,
     case when (v_salin ->> 'pesan')::boolean then coalesce(v_a.wa_admin, '') else '' end,
     case when (v_salin ->> 'bank')::boolean then coalesce(v_a.bank_nama, '') else '' end,
     case when (v_salin ->> 'bank')::boolean then coalesce(v_a.bank_no_rek, '') else '' end,
     case when (v_salin ->> 'bank')::boolean then coalesce(v_a.bank_atas_nama, '') else '' end,
     case when (v_salin ->> 'pesan')::boolean then coalesce(v_a.template_wa_konfirmasi, '') else '' end,
     case when (v_salin ->> 'pesan')::boolean then coalesce(v_a.template_wa_tolak, '') else '' end,
     case when (v_salin ->> 'tampilan')::boolean then coalesce(v_a.logo_url, '') else '' end,
     case when (v_salin ->> 'tampilan')::boolean then coalesce(v_a.bg_url, '') else '' end,
     '');

  if v_src is not null and coalesce((v_salin ->> 'jenis')::boolean, false) then
    insert into public.lomba_jenis (event_id, kode, nama, harga, prefix, urutan, aktif, nomor_terakhir)
    select v_id, kode, nama, harga, prefix, urutan, aktif, 0 from public.lomba_jenis where event_id = v_src;
  end if;

  for v_email in select distinct public.lomba_rapikan_email(x) from jsonb_array_elements_text(coalesce(p -> 'panitia', '[]'::jsonb)) x
  loop
    insert into public.lomba_event_admin (event_id, email) values (v_id, v_email) on conflict do nothing;
  end loop;
  return public.lomba_ringkas_event(v_id, true);
end;
$$;

create or replace function public.lomba_ubah_event(p_id bigint, p_slug text default null, p_tampil boolean default null)
returns json
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.lomba_wajib_super();
  if not exists (select 1 from public.lomba_event where id = p_id) then
    raise exception 'EVENT_TIDAK_ADA';
  end if;
  update public.lomba_event
     set slug   = case when p_slug is null then slug else public.lomba_cek_slug(p_slug, p_id) end,
         tampil = coalesce(p_tampil, tampil)
   where id = p_id;
  return public.lomba_ringkas_event(p_id, true);
end;
$$;

-- hapus event beserta seluruh isinya; mengembalikan file bukti untuk dihapus dari Storage
create or replace function public.lomba_hapus_event(p_id bigint)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_paths json;
begin
  perform public.lomba_wajib_super();
  select coalesce(json_agg(bukti_path), '[]'::json) into v_paths
    from public.lomba_pendaftaran where event_id = p_id and bukti_path is not null;
  delete from public.lomba_pendaftaran where event_id = p_id;
  delete from public.lomba_seri        where event_id = p_id;
  delete from public.lomba_sesi        where event_id = p_id;
  delete from public.lomba_hari        where event_id = p_id;
  delete from public.lomba_jenis       where event_id = p_id;
  delete from public.lomba_pengaturan  where event_id = p_id;
  delete from public.lomba_event_admin where event_id = p_id;
  delete from public.lomba_event       where id = p_id;
  return json_build_object('bukti_paths', v_paths);
end;
$$;

-- akses admin event: tambah, ganti email, cabut
create or replace function public.lomba_tambah_akses(p_event bigint, p_email text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v text := public.lomba_rapikan_email(p_email);
begin
  perform public.lomba_wajib_super();
  if exists (select 1 from public.lomba_admin where lower(email) = v) then
    raise exception 'EMAIL_SUPER';
  end if;
  insert into public.lomba_event_admin (event_id, email) values (p_event, v);
exception when unique_violation then
  raise exception 'EMAIL_SUDAH_ADA';
end;
$$;

create or replace function public.lomba_ganti_akses(p_event bigint, p_lama text, p_baru text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v text := public.lomba_rapikan_email(p_baru);
begin
  perform public.lomba_wajib_super();
  if exists (select 1 from public.lomba_admin where lower(email) = v) then
    raise exception 'EMAIL_SUPER';
  end if;
  update public.lomba_event_admin set email = v where event_id = p_event and email = lower(btrim(p_lama));
  if not found then
    raise exception 'EVENT_TIDAK_ADA';
  end if;
exception when unique_violation then
  raise exception 'EMAIL_SUDAH_ADA';
end;
$$;

-- p_event kosong = cabut dari SEMUA event
create or replace function public.lomba_cabut_akses(p_event bigint, p_email text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.lomba_wajib_super();
  delete from public.lomba_event_admin
   where email = lower(btrim(p_email)) and (p_event is null or event_id = p_event);
end;
$$;

-- ganti email satu orang di semua event yang dipegangnya
create or replace function public.lomba_ganti_email_panitia(p_lama text, p_baru text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_lama text := lower(btrim(p_lama));
  v      text := public.lomba_rapikan_email(p_baru);
begin
  perform public.lomba_wajib_super();
  if v = v_lama then
    return;
  end if;
  if exists (select 1 from public.lomba_admin where lower(email) = v) then
    raise exception 'EMAIL_SUPER';
  end if;
  delete from public.lomba_event_admin a
   where a.email = v_lama and exists (select 1 from public.lomba_event_admin b where b.event_id = a.event_id and b.email = v);
  update public.lomba_event_admin set email = v where email = v_lama;
end;
$$;

-- semua admin event & event yang dipegang (untuk super admin)
create or replace function public.lomba_daftar_akses()
returns json
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  perform public.lomba_wajib_super();
  return coalesce((
    select json_agg(json_build_object('email', x.email, 'events', x.events) order by x.email)
    from (
      select ea.email, json_agg(json_build_object('id', e.id, 'slug', e.slug, 'nama_event', st.nama_event,
                                                  'tanggal_mulai', st.tanggal_mulai, 'tanggal_selesai', st.tanggal_selesai)
                                order by st.tanggal_mulai nulls last, e.id) as events
        from public.lomba_event_admin ea
        join public.lomba_event e on e.id = ea.event_id
        left join public.lomba_pengaturan st on st.event_id = e.id
       group by ea.email
    ) x), '[]'::json);
end;
$$;

create or replace function public.lomba_simpan_situs(p jsonb)
returns json
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.lomba_wajib_super();
  if p ? 'nama' and btrim(coalesce(p ->> 'nama', '')) = '' then
    raise exception 'DATA_TIDAK_LENGKAP';
  end if;
  update public.lomba_situs set
    nama     = case when p ? 'nama'     then btrim(p ->> 'nama')                   else nama end,
    judul    = case when p ? 'judul'    then btrim(coalesce(p ->> 'judul', ''))    else judul end,
    teks     = case when p ? 'teks'     then btrim(coalesce(p ->> 'teks', ''))     else teks end,
    logo_url = case when p ? 'logo_url' then btrim(coalesce(p ->> 'logo_url', '')) else logo_url end,
    bg_url   = case when p ? 'bg_url'   then btrim(coalesce(p ->> 'bg_url', ''))   else bg_url end,
    updated_at = now()
  where id = 1;
  return public.lomba_info_situs();
end;
$$;

