  (1, 'Event pertama (data lama)',
      coalesce((select '✅ ' || e.slug || ' — ' || st.nama_event
                  from public.lomba_event e join public.lomba_pengaturan st on st.event_id = e.id
                 order by e.id limit 1), '❌ Belum ada')),
  (2, 'Semua data punya event',
      case when not exists (select 1 from public.lomba_pendaftaran where event_id is null)
            and not exists (select 1 from public.lomba_seri where event_id is null)
           then '✅ OK' else '❌ Ada data tanpa event' end),
  (3, 'Jumlah pendaftaran (harus sama dengan sebelum pembaruan)',
      '✅ ' || (select count(*) from public.lomba_pendaftaran)::text),
  (4, 'Super admin',
      coalesce((select '✅ ' || string_agg(email, ', ') from public.lomba_admin), '❌ Belum ada')),
  (5, 'Fungsi multi-event',
      case when to_regprocedure('public.lomba_daftar(text,bigint,text,text,text,text,text,text,uuid,integer,text,bigint)') is not null
            and to_regprocedure('public.lomba_buat_event(jsonb)') is not null
            and to_regprocedure('public.lomba_daftar_event()') is not null
           then '✅ OK' else '❌ Gagal' end),
  (6, 'Pengaturan situs (halaman depan)',
      case when exists (select 1 from public.lomba_situs where id = 1) then '✅ OK' else '❌ Belum ada' end)
