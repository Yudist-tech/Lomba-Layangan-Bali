returns json
language sql
stable
security definer
set search_path = public
as $$
  select json_build_object('id', e.id, 'slug', e.slug, 'tampil', e.tampil)
    from public.lomba_event e where e.slug = lower(btrim(coalesce(p_slug, '')));
$$;

create or replace function public.lomba_info_situs()
returns json
language sql
stable
security definer
set search_path = public
as $$
  select json_build_object('nama', nama, 'judul', judul, 'teks', teks, 'logo_url', logo_url, 'bg_url', bg_url)
    from public.lomba_situs where id = 1;
$$;

-- ringkasan event (dipakai halaman depan & ruang panitia)
create or replace function public.lomba_ringkas_event(p_event bigint, p_admin boolean default false)
returns json
language sql
stable
security definer
set search_path = public
as $$
  with e as (select * from public.lomba_event where id = p_event),
       st as (select * from public.lomba_pengaturan where event_id = p_event),
       aktif as (select seri_id, count(*) as n from public.lomba_pendaftaran
                  where event_id = p_event and status in ('menunggu', 'terkonfirmasi') group by seri_id),
       grup as (select g.* from public.lomba_seri g where g.event_id = p_event and g.sesi_id is not null and g.aktif)
  select json_build_object(
    'id', e.id, 'slug', e.slug, 'tampil', e.tampil,
    'nama_event', st.nama_event, 'penyelenggara', st.penyelenggara, 'lokasi', st.lokasi,
    'logo_url', st.logo_url, 'bg_url', st.bg_url, 'flyer_url', st.flyer_url,
    'tanggal_mulai', st.tanggal_mulai, 'tanggal_selesai', coalesce(st.tanggal_selesai, st.tanggal_mulai),
    'pendaftaran_buka', coalesce(st.pendaftaran_buka and (st.batas_daftar is null or now() <= st.batas_daftar), false),
    'ada_jadwal', exists (select 1 from grup),
    'sisa_slot', coalesce((select sum(greatest(0, g.kuota - coalesce(a.n, 0))) from grup g left join aktif a on a.seri_id = g.id), 0),
    'jumlah_jenis', (select count(*) from public.lomba_jenis j where j.event_id = p_event and j.aktif),
    'harga_min', (select min(j.harga) from public.lomba_jenis j where j.event_id = p_event and j.aktif),
    'peserta', (select count(*) from public.lomba_pendaftaran p where p.event_id = p_event and p.status = 'terkonfirmasi'),
    'menunggu', case when p_admin then (select count(*) from public.lomba_pendaftaran p where p.event_id = p_event and p.status = 'menunggu') end,
    'pemasukan', case when p_admin then (select coalesce(sum(p.harga), 0) from public.lomba_pendaftaran p where p.event_id = p_event and p.status = 'terkonfirmasi') end,
    'panitia', case when p_admin and public.lomba_is_super()
                    then coalesce((select json_agg(ea.email order by ea.email) from public.lomba_event_admin ea where ea.event_id = p_event), '[]'::json) end)
  from e left join st on true;
$$;

