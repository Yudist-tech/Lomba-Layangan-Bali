-- =====================================================================
-- UPLOAD FORM JURI (versi 1.0)
-- Jalankan SETELAH juara.sql dan juri-pantau.sql. Aman dijalankan ulang.
--
-- 1) lomba_form_upload : catatan setiap foto form yang di-upload panitia
--                        (foto asli, juri, jumlah baris, SIAPA yang meng-upload & kapan).
--                        Tidak bisa diubah/dihapus panitia (jejak tetap utuh).
-- 2) Riwayat nilai     : setiap upload & setiap perubahan catatan juri pantau
--                        (tambah / koreksi / hapus) tercatat di lomba_nilai_riwayat
--                        lengkap dengan ID panitia yang melakukannya.
--    Perubahan nilai juri sudah tercatat otomatis oleh juara.sql.
-- =====================================================================

create table if not exists public.lomba_form_upload (
  id          bigint generated by default as identity primary key,
  event_id    bigint not null references public.lomba_event(id) on delete cascade,
  jenis       text not null,
  tipe        text not null check (tipe in ('juri', 'pantau')),
  juri_id     bigint references public.lomba_juri(id) on delete set null,
  pantau_id   bigint references public.lomba_juri_pantau(id) on delete set null,
  juri_nama   text,
  seri        text,
  jumlah      int not null default 0,          -- baris yang disimpan dari form ini
  qr          text,                            -- cocok | manual
  foto        text check (foto is null or (foto like 'data:image/%' and length(foto) < 2500000)),
  oleh        text,                            -- diisi database: akun yang meng-upload
  created_at  timestamptz not null default now()
);
create index if not exists lomba_form_upload_event_idx on public.lomba_form_upload (event_id, created_at desc);

alter table public.lomba_form_upload enable row level security;
drop policy if exists lomba_baca on public.lomba_form_upload;
drop policy if exists lomba_menilai_tambah on public.lomba_form_upload;
create policy lomba_baca on public.lomba_form_upload for select to authenticated using ((select public.lomba_boleh_event(event_id)));
create policy lomba_menilai_tambah on public.lomba_form_upload for insert to authenticated with check ((select public.lomba_boleh_menilai(event_id)));
revoke all on table public.lomba_form_upload from anon;
revoke update, delete on table public.lomba_form_upload from authenticated;
grant select, insert on table public.lomba_form_upload to authenticated;

-- oleh & waktu diisi database (tidak bisa dipalsukan), juri harus milik event yang sama
create or replace function public.lomba_trg_form_upload()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.juri_id is not null and not exists (select 1 from public.lomba_juri where id = new.juri_id and event_id = new.event_id) then raise exception 'JUARA_TIDAK_VALID'; end if;
  if new.pantau_id is not null and not exists (select 1 from public.lomba_juri_pantau where id = new.pantau_id and event_id = new.event_id) then raise exception 'JUARA_TIDAK_VALID'; end if;
  new.oleh := public.lomba_email_saya();
  new.created_at := now();
  new.seri := left(nullif(btrim(coalesce(new.seri, '')), ''), 20);
  return new;
end;
$$;
drop trigger if exists lomba_form_upload_bi on public.lomba_form_upload;
create trigger lomba_form_upload_bi before insert on public.lomba_form_upload
  for each row execute function public.lomba_trg_form_upload();

-- upload → riwayat (lama = id upload, baru = jumlah baris)
create or replace function public.lomba_trg_form_upload_riwayat()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.lomba_catat_nilai(new.event_id, new.jenis, null, 'upload', new.juri_nama, new.id::int, new.jumlah,
          case when new.tipe = 'juri' then 'form juri nilai' else 'form juri pantau' end || coalesce(' · seri ' || new.seri, ''));
  return null;
end;
$$;
drop trigger if exists lomba_form_upload_ai on public.lomba_form_upload;
create trigger lomba_form_upload_ai after insert on public.lomba_form_upload
  for each row execute function public.lomba_trg_form_upload_riwayat();

-- catatan juri pantau: tambah / koreksi / hapus → riwayat
create or replace function public.lomba_trg_riwayat_pantau()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  r record; p record; v_nama text; v_ket text;
begin
  r := coalesce(new, old);
  if tg_op = 'UPDATE' and new.teks is not distinct from old.teks then return null; end if;
  select event_id, jenis, nomor_layangan into p from public.lomba_pendaftaran where id = r.pendaftaran_id;
  if p.event_id is null then return null; end if;
  select nama into v_nama from public.lomba_juri_pantau where id = r.pantau_id;
  v_ket := case tg_op when 'INSERT' then 'tambah: ' || new.teks
                      when 'UPDATE' then 'koreksi: ' || old.teks || ' → ' || new.teks
                      else 'hapus: ' || old.teks end;
  perform public.lomba_catat_nilai(p.event_id, p.jenis, p.nomor_layangan, 'pantau', coalesce(v_nama, 'Juri pantau'), null, null, left(v_ket, 400));
  return null;
end;
$$;
drop trigger if exists lomba_riwayat_pantau_aiud on public.lomba_catatan_pantau;
create trigger lomba_riwayat_pantau_aiud after insert or update or delete on public.lomba_catatan_pantau
  for each row execute function public.lomba_trg_riwayat_pantau();

revoke all on function public.lomba_trg_form_upload() from public, anon, authenticated;
revoke all on function public.lomba_trg_form_upload_riwayat() from public, anon, authenticated;
revoke all on function public.lomba_trg_riwayat_pantau() from public, anon, authenticated;

-- Pemeriksaan
select '✅ Tabel upload form siap' as hasil
where exists (select 1 from information_schema.tables where table_schema = 'public' and table_name = 'lomba_form_upload')
union all
select '✅ Riwayat upload aktif'
where exists (select 1 from pg_trigger where tgname = 'lomba_form_upload_ai')
union all
select '✅ Riwayat catatan juri pantau aktif'
where exists (select 1 from pg_trigger where tgname = 'lomba_riwayat_pantau_aiud');
