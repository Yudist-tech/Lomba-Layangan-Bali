-- =====================================================================
-- BUKTI SELESAI DICEK (versi 1.0)
-- Jalankan SETELAH multi-event.sql. Aman dijalankan ulang (idempotent).
--
-- Panitia bisa menandai satu kelompok "Bukti Transfer Sama" / "Bukti Transfer Mirip"
-- sebagai SELESAI dicek. Yang disimpan: anggota kelompok saat ditandai.
-- Bila kemudian ada pendaftaran baru yang masuk ke kelompok itu, aplikasi
-- otomatis mengembalikannya ke tab TERBARU untuk dicek ulang.
-- =====================================================================

create table if not exists public.lomba_bukti_selesai (
  id          bigint generated by default as identity primary key,
  event_id    bigint not null references public.lomba_event(id) on delete cascade,
  jenis       text not null check (jenis in ('sama', 'mirip')),
  anggota     uuid[] not null,            -- id pendaftaran di kelompok saat ditandai selesai
  oleh        text,                       -- diisi otomatis: akun yang menandai
  created_at  timestamptz not null default now()
);
create index if not exists lomba_bukti_selesai_event_idx on public.lomba_bukti_selesai (event_id);

alter table public.lomba_bukti_selesai enable row level security;
drop policy if exists lomba_admin_kelola on public.lomba_bukti_selesai;
create policy lomba_admin_kelola on public.lomba_bukti_selesai for all to authenticated
  using ((select public.lomba_boleh_event(event_id)))
  with check ((select public.lomba_boleh_event(event_id)));

-- "oleh" & waktu diisi database, tidak bisa dipalsukan dari aplikasi
create or replace function public.lomba_trg_bukti_selesai()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.oleh := public.lomba_email_saya();
  new.created_at := now();
  return new;
end;
$$;
drop trigger if exists lomba_bukti_selesai_bi on public.lomba_bukti_selesai;
create trigger lomba_bukti_selesai_bi before insert on public.lomba_bukti_selesai
  for each row execute function public.lomba_trg_bukti_selesai();

revoke all on table public.lomba_bukti_selesai from anon;
revoke update on table public.lomba_bukti_selesai from authenticated;
grant select, insert, delete on table public.lomba_bukti_selesai to authenticated;
revoke all on function public.lomba_trg_bukti_selesai() from public, anon, authenticated;

-- Pemeriksaan
select '✅ Tabel bukti selesai dicek siap' as hasil
where exists (select 1 from information_schema.tables where table_schema = 'public' and table_name = 'lomba_bukti_selesai')
union all
select '✅ Pencatat panitia aktif'
where exists (select 1 from pg_trigger where tgname = 'lomba_bukti_selesai_bi');
